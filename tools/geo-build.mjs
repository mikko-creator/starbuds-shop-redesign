// geo-build.mjs (FINDER lane, REVISION-1 R1.3). Node builtins only. Run once; the outputs are committed data.
//   node tools/geo-build.mjs [--refresh-geo] [--refresh-atlas]
//
// 1. Fetches us-atlas@3.0.1 states-albers-10m.json (+ its ISC LICENSE) from cdn.jsdelivr.net into src/content/vendor/
//    (skipped when the files are already there).
// 2. Geocodes the 12 site.json store addresses with Nominatim, one request per second at most, with the project
//    User-Agent and no e-mail in any header. Results -> src/content/geo.json {slug:{lat,lon,precision,query,display_name}}.
//    Existing entries are kept (no request) unless --refresh-geo. Order of queries per store: the full address; the
//    address with the unit/suite part removed (still precision 'address'); then "City, ST ZIP" (precision 'city').
// 3. Decodes the TopoJSON (quantized, delta-encoded arcs) to SVG path data for the lower-48 states + DC, projects the
//    store points with the lower-48 branch of d3.geoAlbersUsa (conic equal-area, parallels 29.5/45.5, rotate [96,0],
//    center [-0.6,38.7], scale 1300, translate [487.5,305]) and writes src/content/vendor/us-map.json.
// 4. PROOF: every store point must fall inside its own state's path bbox AND inside its polygon (even-odd test), and a
//    control point with a deliberately wrong longitude must fall outside. Exits 1 if any check fails.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const VENDOR = path.join(ROOT, 'src/content/vendor');
const GEO = path.join(ROOT, 'src/content/geo.json');
const MAP = path.join(VENDOR, 'us-map.json');
const ATLAS_VER = '3.0.1';
const ATLAS_FILE = path.join(VENDOR, 'us-atlas-states-albers-10m.json');
const UA = 'starbuds-shop-redesign-pitch/1.0 (one-off geocode of 12 store addresses)';
const argv = new Set(process.argv.slice(2));
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

const site = JSON.parse(fs.readFileSync(path.join(ROOT, 'src/content/site.json'), 'utf8'));
fs.mkdirSync(VENDOR, { recursive: true });

/* ---------- 1. us-atlas ---------- */
async function getText(url) {
  const r = await fetch(url, { headers: { 'User-Agent': UA } });
  if (!r.ok) throw new Error(`${r.status} ${url}`);
  return r.text();
}
if (argv.has('--refresh-atlas') || !fs.existsSync(ATLAS_FILE)) {
  const base = `https://cdn.jsdelivr.net/npm/us-atlas@${ATLAS_VER}/`;
  fs.writeFileSync(ATLAS_FILE, await getText(base + 'states-albers-10m.json'));
  fs.writeFileSync(path.join(VENDOR, 'us-atlas-LICENSE.txt'), await getText(base + 'LICENSE'));
  fs.writeFileSync(path.join(VENDOR, 'README.md'), `# Vendored map data (FINDER lane)

- \`us-atlas-states-albers-10m.json\`: us-atlas@${ATLAS_VER} \`states-albers-10m.json\`, fetched ${new Date().toISOString().slice(0, 10)}
  from ${base}states-albers-10m.json. Licence: ISC (\`us-atlas-LICENSE.txt\`, copied from the package). The shapes
  derive from the U.S. Census Bureau cartographic boundary files.
- \`us-map.json\`: generated by \`tools/geo-build.mjs\` from the file above (SVG path data for the lower-48 states and
  DC, viewBox 0 0 975 610) plus the projected store points from \`../geo.json\` (Nominatim / OpenStreetMap data,
  ODbL; geocoded once).
`);
  console.log('atlas: fetched us-atlas@' + ATLAS_VER);
} else console.log('atlas: cached ' + path.relative(ROOT, ATLAS_FILE));

/* ---------- 2. geocode ---------- */
const geo = fs.existsSync(GEO) ? JSON.parse(fs.readFileSync(GEO, 'utf8')) : {};
let lastReq = 0;
async function nominatim(q) {
  const wait = lastReq + 1100 - Date.now();
  if (wait > 0) await sleep(wait);
  lastReq = Date.now();
  const url = 'https://nominatim.openstreetmap.org/search?format=jsonv2&countrycodes=us&limit=1&q=' + encodeURIComponent(q);
  const r = await fetch(url, { headers: { 'User-Agent': UA, 'Accept-Language': 'en' } });
  if (!r.ok) throw new Error(`nominatim ${r.status} for ${q}`);
  const j = await r.json();
  return j && j[0] ? j[0] : null;
}
const stripUnit = (line) => line.replace(/,?\s*(unit|suite|ste\.?|#)\s*[\w-]+\s*$/i, '').trim();
let requests = 0;
for (const s of site.stores) {
  if (geo[s.slug] && !argv.has('--refresh-geo')) continue;
  const [street, cityLine] = s.address;
  const tries = [
    { q: `${street}, ${cityLine}`, precision: 'address' },
    { q: `${stripUnit(street)}, ${cityLine}`, precision: 'address' },
    { q: cityLine, precision: 'city' },
  ].filter((t, i, a) => a.findIndex((u) => u.q === t.q) === i);
  let hit = null;
  for (const t of tries) {
    requests++;
    const r = await nominatim(t.q);
    // an address query that only resolves to a town or postcode is not an address hit
    const addrish = r && (t.precision === 'city' || !['city', 'town', 'village', 'administrative', 'postcode', 'county', 'state'].includes(r.addresstype || r.type));
    console.log(`geocode ${s.slug.padEnd(28)} ${r ? (addrish ? 'hit ' : 'weak') : 'miss'} ${t.q}${r ? '  -> ' + (r.addresstype || r.type) : ''}`);
    if (r && addrish) { hit = { lat: +r.lat, lon: +r.lon, precision: t.precision, query: t.q, display_name: r.display_name }; break; }
  }
  if (!hit) { console.error('FAIL: no geocode for ' + s.slug); process.exitCode = 1; continue; }
  geo[s.slug] = hit;
}
const ordered = Object.fromEntries(site.stores.filter((s) => geo[s.slug]).map((s) => [s.slug, geo[s.slug]]));
fs.writeFileSync(GEO, JSON.stringify(ordered, null, 2) + '\n');
console.log(`geo.json: ${Object.keys(ordered).length} stores (${requests} Nominatim requests this run)`);

/* ---------- 3. TopoJSON -> SVG paths ---------- */
const topo = JSON.parse(fs.readFileSync(ATLAS_FILE, 'utf8'));
const [sx, sy] = topo.transform ? topo.transform.scale : [1, 1];
const [tx, ty] = topo.transform ? topo.transform.translate : [0, 0];
const arcs = topo.arcs.map((arc) => {
  let x = 0, y = 0;
  return arc.map(([dx, dy]) => { x += dx; y += dy; return [x * sx + tx, y * sy + ty]; });
});
// simplify each arc once (shared borders stay identical): drop points closer than TOL to the last kept point
const TOL = 0.45;
const simple = arcs.map((a) => {
  const out = [a[0]];
  for (let i = 1; i < a.length - 1; i++) { const l = out[out.length - 1]; if (Math.hypot(a[i][0] - l[0], a[i][1] - l[1]) >= TOL) out.push(a[i]); }
  out.push(a[a.length - 1]);
  return out;
});
const arcPts = (i, set) => (i >= 0 ? set[i] : set[~i].slice().reverse());
const ringPts = (ring, set) => ring.reduce((acc, i, k) => acc.concat(k ? arcPts(i, set).slice(1) : arcPts(i, set)), []);
const polys = (g) => (g.type === 'Polygon' ? [g.arcs] : g.type === 'MultiPolygon' ? g.arcs : []);
const r1 = (n) => Math.round(n * 10) / 10;
// absolute coords rounded to 0.1 first, then written as relative moves in tenths, so no rounding error accumulates
// t is an integer count of tenths: 20 -> "2", 5 -> ".5", -15 -> "-1.5", -5 -> "-.5"
const num = (t) => { const neg = t < 0, a = Math.abs(t), i = Math.floor(a / 10), f = a % 10; return (neg ? '-' : '') + (i ? String(i) : f ? '' : '0') + (f ? '.' + f : ''); };
function pathD(rings, close = true) {
  return rings.map((pts) => {
    const q = pts.map((p) => [Math.round(p[0] * 10), Math.round(p[1] * 10)]);
    let d = 'M' + num(q[0][0]) + ' ' + num(q[0][1]) + 'l';
    const parts = [];
    for (let i = 1; i < q.length; i++) { const dx = q[i][0] - q[i - 1][0], dy = q[i][1] - q[i - 1][1]; if (dx || dy) parts.push(num(dx) + ' ' + num(dy)); }
    return d + parts.join(' ') + (close ? 'z' : '');
  }).join('');
}
const FIPS = { MS: '28', OK: '40', MD: '24', NY: '36' };
const DROP = new Set(['02', '15', '60', '66', '69', '72', '78']); // not lower-48
const states = [];
for (const g of topo.objects.states.geometries) {
  if (DROP.has(g.id)) continue;
  const fullRings = polys(g).flatMap((p) => p.map((r) => ringPts(r, arcs)));
  const simpleRings = polys(g).flatMap((p) => p.map((r) => ringPts(r, simple)));
  let x0 = Infinity, y0 = Infinity, x1 = -Infinity, y1 = -Infinity;
  for (const ring of fullRings) for (const [x, y] of ring) { x0 = Math.min(x0, x); y0 = Math.min(y0, y); x1 = Math.max(x1, x); y1 = Math.max(y1, y); }
  states.push({ id: g.id, name: g.properties && g.properties.name, d: pathD(simpleRings), bbox: [r1(x0), r1(y0), r1(x1), r1(y1)], _rings: fullRings });
}
// outline of the lower-48 (coasts + land borders): the arcs that only one kept state uses (topojson.mesh a === b)
const arcUse = new Map();
for (const g of topo.objects.states.geometries) {
  if (DROP.has(g.id)) continue;
  for (const p of polys(g)) for (const r of p) for (const i of r) { const k = i >= 0 ? i : ~i; arcUse.set(k, (arcUse.get(k) || 0) + 1); }
}
const coast = pathD([...arcUse].filter(([, n]) => n === 1).map(([k]) => simple[k]), false);

/* ---------- projection: d3.geoAlbersUsa lower-48 branch ---------- */
const RAD = Math.PI / 180;
function albers() {
  const p0 = 29.5 * RAD, p1 = 45.5 * RAD;
  const sy0 = Math.sin(p0), n = (sy0 + Math.sin(p1)) / 2, c = 1 + sy0 * (2 * n - sy0), r0 = Math.sqrt(c) / n;
  const raw = (l, p) => { const r = Math.sqrt(c - 2 * n * Math.sin(p)) / n; return [r * Math.sin(l * n), r0 - r * Math.cos(l * n)]; };
  const k = 1300, T = [487.5, 305];
  const cr = raw(-0.6 * RAD, 38.7 * RAD); // d3 applies center to the raw projection, unrotated
  const dx = T[0] - k * cr[0], dy = T[1] + k * cr[1];
  return (lon, lat) => {
    let l = (lon + 96) * RAD; // rotate [96, 0]
    if (l > Math.PI) l -= 2 * Math.PI; else if (l < -Math.PI) l += 2 * Math.PI;
    const [x, y] = raw(l, lat * RAD);
    return [dx + k * x, dy - k * y];
  };
}
const project = albers();
const inBox = ([x, y], b) => x >= b[0] && x <= b[2] && y >= b[1] && y <= b[3];
function inPoly([x, y], rings) { // even-odd over all rings (holes handled)
  let inside = false;
  for (const ring of rings) for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [xi, yi] = ring[i], [xj, yj] = ring[j];
    if ((yi > y) !== (yj > y) && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) inside = !inside;
  }
  return inside;
}

/* ---------- 4. proof ---------- */
const byId = Object.fromEntries(states.map((s) => [s.id, s]));
const points = {};
let fail = 0;
console.log('\nPROOF (projected point vs its own state, viewBox 0 0 975 610)');
for (const s of site.stores) {
  const g = ordered[s.slug];
  if (!g) { fail++; continue; }
  const st = byId[FIPS[s.state]];
  const p = project(g.lon, g.lat);
  const box = inBox(p, st.bbox), poly = inPoly(p, st._rings);
  if (!box || !poly) fail++;
  points[s.slug] = [r1(p[0]), r1(p[1])];
  console.log(`${box && poly ? 'ok  ' : 'FAIL'} ${s.slug.padEnd(28)} ${s.state} lat ${g.lat.toFixed(5)} lon ${g.lon.toFixed(5)} -> (${p[0].toFixed(1)}, ${p[1].toFixed(1)})  bbox ${st.name} [${st.bbox.join(', ')}] ${box ? 'inside' : 'OUTSIDE'}, polygon ${poly ? 'inside' : 'OUTSIDE'}  [${g.precision}]`);
}
// controls: the right latitude with a deliberately wrong longitude must land outside the state
const controls = [
  { slug: 'pearl', state: 'MS', dLon: +8 },
  { slug: 'lawton-dispensary', state: 'OK', dLon: -8 },
  { slug: 'baltimore-dispensary', state: 'MD', dLon: -6 },
  { slug: 'buffalo-dispensary', state: 'NY', dLon: -6 },
];
for (const c of controls) {
  const g = ordered[c.slug];
  if (!g) continue;
  const st = byId[FIPS[c.state]];
  const p = project(g.lon + c.dLon, g.lat);
  const box = inBox(p, st.bbox), poly = inPoly(p, st._rings);
  if (box || poly) fail++;
  console.log(`${!box && !poly ? 'ok  ' : 'FAIL'} control ${c.slug} lon ${(g.lon + c.dLon).toFixed(3)} (wrong by ${c.dLon}) -> (${p[0].toFixed(1)}, ${p[1].toFixed(1)}) ${st.name} bbox ${box ? 'INSIDE' : 'outside'}, polygon ${poly ? 'INSIDE' : 'outside'} (must be outside)`);
}
// self-consistency only (not an external check): the rotated centre must map to the translate point
const ctr = project(-96.6, 38.7);
const ctrOk = Math.abs(ctr[0] - 487.5) < 1e-6 && Math.abs(ctr[1] - 305) < 1e-6;
if (!ctrOk) fail++;
console.log(`${ctrOk ? 'ok  ' : 'FAIL'} centre [-96.6, 38.7] -> (${ctr[0].toFixed(4)}, ${ctr[1].toFixed(4)}) (must be the translate 487.5, 305)`);

// graticule (every 5 degrees) with the same projection, sampled every degree: decoration for the engraved look
const grat = [];
for (let lon = -125; lon <= -65; lon += 5) { const l = []; for (let lat = 23; lat <= 51.001; lat += 1) l.push(project(lon, lat)); grat.push(l); }
for (let lat = 25; lat <= 50; lat += 5) { const l = []; for (let lon = -128; lon <= -62.001; lon += 1) l.push(project(lon, lat)); grat.push(l); }

const out = {
  source: `us-atlas@${ATLAS_VER} states-albers-10m.json (ISC), simplified (arc tolerance ${TOL}), lower-48 + DC`,
  viewBox: [0, 0, 975, 610],
  coast,
  graticule: pathD(grat, false),
  states: states.map(({ _rings, ...s }) => s),
  points,
};
fs.writeFileSync(MAP, JSON.stringify(out) + '\n');
console.log(`\nus-map.json: ${states.length} shapes, ${(fs.statSync(MAP).size / 1024).toFixed(1)} KB; path data ${(states.reduce((a, s) => a + s.d.length, 0) / 1024).toFixed(1)} KB`);
console.log(fail ? `PROOF FAILED (${fail})` : 'PROOF PASSED: every store inside its own state (bbox + polygon); every wrong-longitude control outside');
if (fail) process.exit(1);
